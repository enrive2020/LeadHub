"""Ошибки при работе с LLM.

Те же две категории, что и у остальных внешних сервисов (см. pipeline/errors.py),
плюс одна специфическая для моделей: ответ пришёл, но он бессмысленный.
"""


class LLMError(Exception):
    """Базовая ошибка работы с моделью."""


class LLMUnavailable(LLMError):
    """Временный сбой: сеть, перегрузка, превышен лимит запросов.

    Имеет смысл повторить. `retry_after` — если провайдер сам назвал срок.
    """

    def __init__(self, message: str, retry_after: float | None = None) -> None:
        super().__init__(message)
        self.retry_after = retry_after


class LLMRejected(LLMError):
    """Повтор не поможет: неверный ключ, нет доступа к модели, кончились деньги.

    Отдельный класс нужен, чтобы не жечь попытки и не тратить деньги впустую
    на запросы, которые заведомо не пройдут.
    """


class LLMBadOutput(LLMError):
    """Модель ответила, но ответ не соответствует контракту.

    Это НЕ сбой сервиса — запрос прошёл, деньги списаны, текст получен.
    Просто текст оказался не тем, что мы просили: не JSON, нет обязательного
    поля, значение вне допустимого набора.

    Отдельный класс важен, потому что лечится это иначе, чем сетевая ошибка:
    не «подождать и повторить то же самое», а «переспросить, объяснив,
    что было не так».
    """
