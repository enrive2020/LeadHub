"""Контракт провайдера языковой модели.

Весь остальной код знает только этот интерфейс и понятия не имеет, кто за ним
стоит: Gemini, Claude, GPT, локальная модель через Ollama или заглушка.

Что это даёт на практике:
  * разработка и тесты идут без ключей и без единого потраченного токена;
  * смена провайдера — одна строка в .env, а не переписывание проекта;
  * можно заставить "модель" вернуть мусор и проверить, как система это
    переживёт. На реальном API такое не воспроизвести по команде, а именно
    эти сценарии и ломают самодельные интеграции.
"""

from abc import ABC, abstractmethod


class LLMProvider(ABC):
    """Минимальный интерфейс: отправить два текста, получить один."""

    #: Человекочитаемое имя — попадает в логи и сохраняется рядом с результатом.
    #: Знать, какая модель выдала оценку, обязательно: сменишь модель — и
    #: старые оценки станут несравнимы с новыми.
    name: str

    @abstractmethod
    def complete(
        self,
        *,
        system: str,
        user: str,
        temperature: float,
        max_tokens: int,
    ) -> str:
        """Отправляет запрос модели и возвращает её ответ как СЫРОЙ текст.

        Намеренно возвращается строка, а не разобранный объект. Разбор — это
        уже толкование ответа, и живёт оно в app/ai/, вместе со знанием о том,
        что мы вообще спрашивали.

        Параметры:
          system — инструкция "кто ты и как себя ведёшь", наш текст;
          user   — данные для обработки, текст постороннего человека;
          temperature — насколько модели позволено "фантазировать" (см. ниже);
          max_tokens  — потолок длины ответа.

        ПРО TEMPERATURE. Модель на каждом шаге выбирает следующее слово из
        распределения вероятностей. temperature=0 — всегда самое вероятное
        слово: ответы предсказуемые и почти воспроизводимые. Чем выше, тем
        охотнее выбирается что-то менее очевидное: текст живее, но и уехать
        в сторону легче.
        Для классификации нужна предсказуемость, а не творчество, поэтому
        держим низкую. Для сочинения текстов уместнее выше — но у нас один
        запрос делает и то, и другое, так что низкая безопаснее: лучше
        суховатый черновик письма, чем случайная оценка лида.

        ПРО TOKENS. Модель работает не с буквами и не со словами, а с
        токенами — кусками текста примерно в 3-4 символа для русского.
        Оплата идёт за токены: и за отправленные, и за полученные. Отсюда
        два практических вывода: не слать в промт лишнего и всегда ставить
        потолок ответа, чтобы разговорчивая модель не выставила счёт.

        Бросает:
          LLMUnavailable — временный сбой, повтор имеет смысл;
          LLMRejected    — повтор бессмыслен (ключ, доступ, деньги).
        """
        raise NotImplementedError
