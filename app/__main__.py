"""Точка входа: `python -m app`.

Можно было бы запускать через `uvicorn app.api.app:app --host ... --port ...`,
но тогда адрес и порт пришлось бы каждый раз писать руками, и они разъехались
бы с .env. Здесь настройки берутся из одного источника правды.
"""

import uvicorn

from app.config import settings

if __name__ == "__main__":
    uvicorn.run(
        # Строкой, а не объектом: только так работает автоперезагрузка —
        # uvicorn должен уметь переимпортировать модуль после правки файла.
        "app.api.app:app",
        host=settings.host,
        port=settings.port,
        # В разработке сервер сам перезапускается при изменении кода.
        # В проде это выключено: лишний расход и риск перезапуска на живых данных.
        reload=settings.is_dev,
        log_config=None,  # не даём uvicorn перебивать наш формат логов
    )
