"""Лид — центральное понятие системы.

САМОЕ ВАЖНОЕ АРХИТЕКТУРНОЕ РЕШЕНИЕ ПРОЕКТА живёт здесь.

Заявка с сайта, сообщение в Telegram и письмо с Авито приходят в совершенно
разных форматах. Если пустить эти форматы дальше в систему, то воркер, Google
Sheets и промт для LLM будут завалены ветвлениями "если источник такой, то поле
называется так". Каждый новый канал будет ломать существующие.

Поэтому каждый источник обязан привести свою заявку к ОДНОМУ типу `Lead`.
Дальше по системе ходит только он. Источник превращается из ветки кода
в обычное строковое поле `source` — то есть в данные.

    сайт     ─┐
    Telegram ─┼─> адаптер источника ─> Lead ─> вся остальная система
    Авито    ─┘   (единственное место,        (не знает, откуда лид)
                   знающее про формат)
"""

import hashlib
import json
import uuid
from datetime import UTC, datetime
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field

from app.domain.normalize import collapse_spaces, normalize_email, normalize_phone


class LeadStatus(str, Enum):
    """Состояние лида в пайплайне.

    Наследуемся от str, чтобы значение можно было напрямую писать в БД и JSON,
    а в коде пользоваться понятным LeadStatus.NEW вместо строки "new".

    Жизненный цикл:
        NEW ──> PROCESSING ──> DONE
                    │
                    └────────> FAILED  (кончились попытки; лид не потерян,
                                        лежит в базе и ждёт разбора руками)
    """

    NEW = "new"                # принят и сохранён, воркер ещё не брал
    PROCESSING = "processing"  # воркер взял в работу прямо сейчас
    DONE = "done"              # все шаги отработали успешно
    FAILED = "failed"          # попытки исчерпаны, нужен человек


class Lead(BaseModel):
    """Единый формат заявки, независимый от источника."""

    # Свой идентификатор, а не автоинкремент из БД: он известен сразу,
    # ещё до записи, его можно вернуть отправителю и написать в лог.
    id: str = Field(default_factory=lambda: uuid.uuid4().hex)

    source: str                  # "site_form", "telegram", ...
    dedup_key: str               # ключ защиты от дублей, см. make_dedup_key()

    # Контакты и суть заявки. Всё необязательно: реальные формы бывают
    # какими угодно, и упасть из-за отсутствия email мы не имеем права —
    # неполный лид всё равно ценнее потерянного.
    name: str | None = None
    phone: str | None = None
    email: str | None = None
    message: str | None = None

    # Исходные данные ровно в том виде, в каком пришли.
    # Если завтра выяснится, что в форме было поле "бюджет", которое мы
    # не разбирали, — оно уже сохранено, и старые лиды не потеряны.
    raw: dict[str, Any] = Field(default_factory=dict)

    received_at: datetime = Field(default_factory=lambda: datetime.now(UTC))
    status: LeadStatus = LeadStatus.NEW

    def short_repr(self) -> str:
        """Компактное представление для логов."""
        contact = self.phone or self.email or "без контакта"
        return f"Lead({self.id[:8]}, {self.source}, {self.name or 'без имени'}, {contact})"


def _canonical_json(payload: dict[str, Any]) -> str:
    """Стабильное строковое представление словаря.

    Обычный json.dumps не годится: {"a":1,"b":2} и {"b":2,"a":1} — один и тот же
    словарь, но разные строки, а значит и разные хеши. sort_keys это чинит.
    """
    return json.dumps(payload, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def make_dedup_key(
    source: str,
    external_id: str | None = None,
    payload: dict[str, Any] | None = None,
    *,
    window_days: int = 0,
    moment: datetime | None = None,
) -> str:
    """Строит ключ, по которому система узнаёт повторно присланную заявку.

    ЗАЧЕМ. Одна и та же заявка приходит дважды чаще, чем кажется:
      * пользователь нажал "Отправить" два раза, потому что "чё-то не работает";
      * сеть моргнула, отправитель не получил наш 200 OK и повторил запрос;
      * Telegram не дождался ответа за 5 секунд и переслал апдейт заново.
    Без защиты владелец получит два одинаковых лида и дважды позвонит клиенту.

    ИДЕМПОТЕНТНОСТЬ — свойство операции давать один и тот же результат при
    повторном выполнении. Мы делаем приём идемпотентным: dedup_key лежит в БД
    под UNIQUE-индексом, и вторая вставка с тем же ключом просто ничего не
    меняет. Проверку выполняет база, а не наш код: "проверил SELECT-ом, потом
    вставил" — классическая гонка, два одновременных запроса пройдут проверку оба.

    ДВЕ СТРАТЕГИИ:
      1. Есть external_id (id сообщения в Telegram, номер заявки в CRM) —
         используем его. Источник сам гарантирует уникальность, поэтому окно
         времени здесь НЕ применяется: сообщение №42 навсегда одно и то же.
      2. Нет — берём хеш содержимого плюс номер временного окна.

    ОКНО ДЕДУПЛИКАЦИИ (window_days). Хеш содержимого без окна значил бы:
    клиент, приславший буквально тот же текст через месяц, — дубль. Это уже
    не защита от двойного клика, а потерянная повторная заявка. Поэтому в ключ
    подмешивается номер окна: внутри окна одинаковое содержимое — один лид,
    в следующем окне — уже новый.

    ЧЕСТНОЕ ОГРАНИЧЕНИЕ: у окна есть граница. Двойной клик ровно на стыке
    окон (последняя секунда одного, первая другого) даст два лида. Редко и
    дёшево: владелец один раз увидит дубль. Обратная ошибка — молча проглотить
    настоящую повторную заявку — дороже. Из двух зол выбираем видимое.

    window_days=0 отключает окно (поведение «как раньше»). Значение приходит
    параметром, а не из настроек: domain не импортирует ничего из проекта,
    и это правило дороже, чем удобство одного импорта.
    """
    if external_id:
        raw_key = f"{source}|id|{external_id}"
    else:
        bucket = ""
        if window_days > 0:
            at = moment or datetime.now(UTC)
            # Номер окна = порядковый номер дня с эпохи, делённый на ширину.
            # Целочисленно: все моменты внутри окна дают одно число.
            bucket_index = int(at.timestamp()) // 86400 // window_days
            bucket = f"|w{bucket_index}"
        raw_key = f"{source}|hash|{_canonical_json(payload or {})}{bucket}"

    # sha256 даёт короткий ключ фиксированной длины вместо простыни на 2 КБ,
    # которую неудобно индексировать и невозможно читать глазами в логе.
    return hashlib.sha256(raw_key.encode("utf-8")).hexdigest()


def build_lead(
    *,
    source: str,
    raw: dict[str, Any],
    name: str | None = None,
    phone: str | None = None,
    email: str | None = None,
    message: str | None = None,
    external_id: str | None = None,
    dedup_window_days: int = 0,
) -> Lead:
    """Собирает Lead из разобранных полей: нормализует контакты и считает dedup_key.

    Единственный правильный способ создать лид. Адаптеры источников вызывают
    именно его, поэтому нормализация и защита от дублей работают одинаково
    для всех каналов — их нельзя случайно забыть в новом источнике.

    Звёздочка в сигнатуре запрещает позиционные аргументы: build_lead("site",
    "Иван", "+7...") легко перепутать местами, build_lead(source=..., name=...)
    — нет.
    """
    return Lead(
        source=source,
        dedup_key=make_dedup_key(
            source,
            external_id=external_id,
            payload=raw,
            window_days=dedup_window_days,
        ),
        name=collapse_spaces(name),
        phone=normalize_phone(phone),
        email=normalize_email(email),
        message=collapse_spaces(message),
        raw=raw,
    )
