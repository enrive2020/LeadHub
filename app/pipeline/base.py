"""Контракт шага пайплайна.

Шаг — это одно действие над лидом: записать в таблицу, отправить уведомление,
спросить у LLM. Воркер не знает, что именно делает шаг: он умеет только
"выполнить" и разобрать результат.

Благодаря этому добавление шага (или его удаление) не трогает воркер —
меняется только список в registry.py.
"""

from abc import ABC, abstractmethod

from app.domain.lead import Lead


class Step(ABC):
    """Базовый класс для всех шагов обработки."""

    #: Имя шага. Попадает в колонку lead_tasks.step, в логи и в /healthz.
    #: Менять у работающего шага нельзя — в базе останутся задачи со старым
    #: именем, и воркер не найдёт, чем их выполнять.
    name: str

    @abstractmethod
    def run(self, lead: Lead) -> None:
        """Выполняет шаг. Молча вернуться = успех.

        При сбое нужно бросить:
          * RetryableError — если повтор имеет шанс сработать;
          * PermanentError — если не имеет.
        Любое другое исключение воркер считает временным (осторожная позиция:
        лучше зря повторить, чем зря сдаться).

        ВАЖНО ПРО ИДЕМПОТЕНТНОСТЬ. Очередь гарантирует доставку "хотя бы один
        раз" (at-least-once), а не "ровно один раз". Процесс может умереть
        МЕЖДУ успешным действием и отметкой "done" в базе — тогда после
        перезапуска шаг выполнится повторно.

        Гарантировать "ровно один раз" в распределённых системах невозможно
        в принципе, поэтому нормальный подход — делать шаг безопасным для
        повтора. Например, перед записью в таблицу проверять, нет ли там уже
        строки с этим lead_id.
        """
        raise NotImplementedError
