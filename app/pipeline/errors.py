"""Типы ошибок шага.

КЛЮЧЕВАЯ ИДЕЯ: не всякую ошибку имеет смысл повторять.

  * Google Sheets ответил 503 "сервис перегружен" — повторим через пару секунд,
    и всё получится. Это ВРЕМЕННАЯ ошибка.
  * Google Sheets ответил 403 "нет доступа к таблице" — можно повторять до утра,
    доступ от этого не появится. Это ПОСТОЯННАЯ ошибка.

Разница практическая. Повторять постоянную ошибку — значит впустую жечь время,
квоты и (в случае LLM) деньги, а потом всё равно сдаться. Правильнее сразу
положить задачу на полку разбора и показать человеку внятную причину.

Поэтому шаг обязан различать эти два случая сам — только он знает,
что означает ответ его сервиса.
"""


class StepError(Exception):
    """Базовая ошибка шага пайплайна."""


class RetryableError(StepError):
    """Временный сбой: сеть моргнула, сервис перегружен, лимит запросов.

    Воркер повторит попытку с нарастающей задержкой.
    """


class PermanentError(StepError):
    """Повтор не поможет: нет прав, неверный ключ, некорректные данные.

    Воркер сразу отправит задачу в dead letter, не тратя попытки.
    """
