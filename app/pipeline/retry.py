"""Расчёт задержки перед повторной попыткой.

ПОЧЕМУ НЕ "ПОВТОРЯТЬ РАЗ В СЕКУНДУ".

Сервис обычно падает не на секунду, а на минуты. Долбить его раз в секунду
бессмысленно и вредно: мы добавляем нагрузку туда, где и так плохо, и мешаем
ему подняться. Отдельная беда — облачные API с лимитом запросов: упрямые
повторы упираются в лимит, и тогда мы не можем достучаться, даже когда сервис
уже ожил.

ЭКСПОНЕНЦИАЛЬНАЯ ЗАДЕРЖКА (exponential backoff): каждая следующая пауза вдвое
длиннее. 2, 4, 8, 16, 32 секунды. Первые попытки частые — ловим короткие сбои
сети. Дальние редкие — даём сервису спокойно восстановиться.

Потолок обязателен: без него десятая попытка ушла бы на сутки вперёд.

ДЖИТТЕР (jitter) — случайная добавка к задержке. Зачем: если сервис лежал
минуту, к моменту его подъёма накопилась сотня задач, и все они рассчитали
одинаковое время повтора. Все ломанутся одновременно и уронят его снова — это
"эффект громового стада" (thundering herd). Случайный разброс размазывает
нагрузку по времени. Три строки кода, спасающие от самоподдерживающейся аварии.
"""

import random

from app.config import settings

# Доля от задержки, в пределах которой добавляется случайный разброс.
_JITTER_RATIO = 0.25


def compute_delay(attempt: int) -> float:
    """Задержка перед попыткой номер `attempt` (нумерация с 1).

        1 -> ~2 сек     3 -> ~8 сек     5 -> ~32 сек
        2 -> ~4 сек     4 -> ~16 сек    ... но не больше потолка

    Возвращаются секунды с дробной частью — из-за джиттера.
    """
    base = settings.retry_base_delay_seconds
    ceiling = settings.retry_max_delay_seconds

    # 2 ** (attempt - 1): 1, 2, 4, 8, 16 — то самое удвоение.
    delay = min(base * (2 ** (attempt - 1)), ceiling)

    jitter = random.uniform(0, delay * _JITTER_RATIO)
    return delay + jitter
