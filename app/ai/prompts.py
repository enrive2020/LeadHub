def render_lead(
    *,
    source: str,
    name: str | None,
    phone: str | None,
    email: str | None,
    message: str | None,
) -> str:
    """Готовит данные заявки для сообщения роли user.

    Поля подписаны и разделены явно. Так модель понимает структуру, а мы
    получаем чёткую границу: вот здесь начинаются данные постороннего
    человека. Слепить всё в одну строку — прямой путь к тому, что текст
    клиента будет прочитан как продолжение наших инструкций.
    """
    parts = [
        "Заявка для оценки.",
        "",
        f"Источник: {source}",
        f"Имя: {name or 'не указано'}",
        f"Телефон: {phone or 'не указан'}",
        f"Email: {email or 'не указан'}",
        "Сообщение клиента:",
        (message or "(пустое сообщение)"),
    ]
    return "\n".join(parts)


def render_repair_request(previous_answer: str, problem: str) -> str:
    """Просьба переделать ответ, который не прошёл проверку.

    ПОЧЕМУ НЕ ПРОСТО ПОВТОРИТЬ ТОТ ЖЕ ЗАПРОС. Повтор без изменений — это
    ставка на случайность: те же входные данные, тот же результат, разве что
    повезёт. Показав модели её собственный ответ и конкретную претензию, мы
    даём ей то, чего не хватало, — обратную связь. Такой повтор срабатывает
    ощутимо чаще.

    Ответ модели урезаем: если она выдала простыню, целиком слать её обратно
    значит оплатить те же токены дважды.
    """
    return (
        "Твой предыдущий ответ не соответствует требуемому формату.\n\n"
        f"Что было не так: {problem}\n\n"
        f"Твой ответ был:\n{previous_answer[:1000]}\n\n"
        "Верни ИСПРАВЛЕННЫЙ ответ: один валидный объект JSON по схеме из "
        "системной инструкции. Без пояснений, без markdown-ограждений."
    )
