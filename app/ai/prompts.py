"""Промты — самая недооценённая часть AI-интеграции.

Промт это не «текст для нейросети», а СПЕЦИФИКАЦИЯ. К нему стоит относиться
как к коду: он лежит в репозитории, меняется через коммиты, и по истории видно,
почему формулировка стала такой.

Отдельный файл нужен именно за этим. Промт, вписанный посреди бизнес-логики,
правится наугад и молча меняет поведение всей системы.
"""

import json

from app.ai.schemas import Qualification


def _schema_block() -> str:
    """Собирает описание контракта ИЗ pydantic-модели, а не переписывает руками.

    Это защита от расхождения. Если продублировать схему текстом, то однажды
    в модель добавят поле, промт останется старым — и начнётся необъяснимое:
    модель отвечает «правильно», а валидация ругается. Здесь источник правды
    один — app/ai/schemas.py.
    """
    schema = Qualification.model_json_schema()
    return json.dumps(schema, ensure_ascii=False, indent=2)


