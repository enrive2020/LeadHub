"""Схема ответа модели — КОНТРАКТ, который она обязана соблюсти.

Это ключевая идея всего AI-слоя. Модель возвращает свободный текст, а нам
нужны данные. Схема — граница между "что-то написала нейросеть" и "значения,
которые можно положить в базу и показать человеку".

Всё, что не проходит проверку, внутрь системы не попадает — ровно как заявка
с сайта не попадает мимо SiteFormPayload. Тот же принцип, тот же pydantic.
"""

from enum import Enum

from pydantic import BaseModel, Field


class LeadGrade(str, Enum):
    """Насколько заявка перспективна.

    Три значения, а не десять: владелец должен понять решение за секунду,
    а модель — уверенно выбрать. Чем больше градаций, тем менее устойчива
    классификация и тем бесполезнее результат.
    """

    HOT = "hot"    # готов покупать: конкретный запрос, бюджет или срочность
    WARM = "warm"  # интерес есть, но нужен разговор
    COLD = "cold"  # спам, ошибка, "просто посмотреть"


class Qualification(BaseModel):
    """Результат работы AI над одной заявкой.

    Ограничения (ge, le, min_length, max_length) — не придирки. Каждое
    закрывает реальный способ, которым модель может выдать формально
    корректный, но бесполезный ответ:
      * score=150 — модель не поняла шкалу;
      * пустой reason — сказала "hot" и не объяснила, доверять нечему;
      * reply_draft на три тысячи символов — такое письмо никто не отправит.
    """

    grade: LeadGrade = Field(
        description="hot — готов покупать; warm — нужен разговор; cold — не целевой"
    )

    score: int = Field(
        ge=0, le=100,
        description="Числовая оценка перспективности от 0 до 100",
    )

    reason: str = Field(
        min_length=3, max_length=300,
        description="Одно-два предложения: почему именно такая оценка",
    )

    reply_draft: str = Field(
        min_length=10, max_length=1000,
        description=(
            "Черновик первого ответа клиенту на русском языке, на «вы», "
            "2–4 предложения, без выдуманных цен и сроков"
        ),
    )
